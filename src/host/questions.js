/**
 * Chapter questions: thin-bordered **position markers** on a page, not text.
 *
 * A question is a rectangle on one page plus a name. It stores no excerpt and no
 * question body: the name only locates the place, the reader jumps there, and a
 * conversation (when the user asks for help) receives one line about it.
 *
 * Stored inside the library so it travels with the books:
 *
 *   <库根>/.pdfdesk/questions/<书>/<章>.json
 *     { format, next, questions: [{ id, name, page, rect, createdAt }] }
 *
 * `next` is the number the next default name (`疑问 N`) takes. Deleting a
 * question does not give its number back, and `next` only ever moves forward.
 *
 * @module dsh-pdf-workbench/questions
 */
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'

/** On-disk schema version. */
export const QUESTIONS_FORMAT = 1

/** Questions kept per chapter: a page mark should stay a mark, not a database. */
export const MAX_QUESTIONS = 500

/** Longest accepted name. */
const MAX_NAME = 80

/** A question id, generated by the browser. */
const ID = /^q-[A-Za-z0-9._-]{1,64}$/

/** A chapter code, canonical form. */
const CODE = /^c\d{2,3}$/

/** One path segment: no separators, no traversal, no drive colon. */
const SEGMENT = /^[^\\/:*?"<>|]{1,200}$/

/**
 * Whether a value can be one directory segment.
 * @param {unknown} value - candidate.
 * @returns {boolean} true when safe.
 */
function isSegment(value) {
  return typeof value === 'string' && SEGMENT.test(value) && value !== '.' && value !== '..'
}

/**
 * One chapter's questions file.
 * @param {string} libraryDir - library root.
 * @param {string} book - book id.
 * @param {string} code - chapter code.
 * @returns {string} absolute path.
 */
export function questionsFile(libraryDir, book, code) {
  return join(libraryDir, '.pdfdesk', 'questions', book, `${code}.json`)
}

/**
 * Clamp one rect into the page. A hand-edited file or a stale layout must not
 * put a mark outside the page.
 * @param {unknown} value - candidate rect.
 * @returns {{ x: number, y: number, w: number, h: number } | null} the rect, or null.
 */
function sanitizeRect(value) {
  if (value === null || typeof value !== 'object') return null
  const x = Number(value.x)
  const y = Number(value.y)
  const w = Number(value.w)
  const h = Number(value.h)
  if (![x, y, w, h].every(item => Number.isFinite(item))) return null
  // A mark with no area is not a mark: the browser never creates one, and a
  // hand-edited file should not smuggle a point in as a rectangle.
  if (w <= 0 || h <= 0) return null
  const left = Math.min(1, Math.max(0, x))
  const top = Math.min(1, Math.max(0, y))
  const width = Math.min(1 - left, Math.max(0.002, w))
  const height = Math.min(1 - top, Math.max(0.002, h))
  const round = number => Math.round(number * 1e6) / 1e6
  return { x: round(left), y: round(top), w: round(width), h: round(height) }
}

/**
 * Keep one stored question if it is usable.
 * @param {unknown} value - stored entry.
 * @param {number} index - its position, for a missing name.
 * @returns {object | null} the question, or null when unusable.
 */
function sanitizeQuestion(value, index) {
  if (value === null || typeof value !== 'object') return null
  const id = typeof value.id === 'string' && ID.test(value.id) ? value.id : ''
  const rect = sanitizeRect(value.rect)
  const page = Math.round(Number(value.page))
  if (id === '' || rect === null || !Number.isFinite(page) || page < 1) return null
  const name = typeof value.name === 'string' && value.name.trim() !== ''
    ? value.name.trim().slice(0, MAX_NAME)
    : `疑问 ${index + 1}`
  const stamp = Number(value.createdAt)
  return {
    id,
    name,
    page,
    rect,
    createdAt: Number.isFinite(stamp) && stamp > 0 ? stamp : Date.now(),
  }
}

/**
 * The number inside a `疑问 N` name, for keeping `next` ahead of hand-edited
 * names.
 * @param {string} name - question name.
 * @returns {number} the number, or 0.
 */
function numberOfName(name) {
  const match = /^疑问\s*(\d+)$/.exec(name)
  return match === null ? 0 : Number(match[1])
}

/**
 * Read one chapter's questions.
 * @param {string} libraryDir - library root.
 * @param {string} book - book id.
 * @param {string} code - chapter code.
 * @returns {Promise<{ format: number, next: number, questions: object[] }>} the stored list (empty when absent).
 */
export async function readQuestions(libraryDir, book, code) {
  if (!isSegment(book) || !CODE.test(code)) return { format: QUESTIONS_FORMAT, next: 1, questions: [] }
  let parsed = null
  try {
    parsed = JSON.parse(await readFile(questionsFile(libraryDir, book, code), 'utf8'))
  } catch {
    return { format: QUESTIONS_FORMAT, next: 1, questions: [] }
  }
  const raw = parsed !== null && typeof parsed === 'object' && Array.isArray(parsed.questions) ? parsed.questions : []
  const questions = []
  const seen = new Set()
  for (const value of raw) {
    const entry = sanitizeQuestion(value, questions.length)
    if (entry === null || seen.has(entry.id)) continue
    seen.add(entry.id)
    questions.push(entry)
    if (questions.length >= MAX_QUESTIONS) break
  }
  const storedNext = Number(parsed !== null && typeof parsed === 'object' ? parsed.next : NaN)
  const next = Math.max(
    Number.isFinite(storedNext) && storedNext > 0 ? Math.round(storedNext) : 1,
    questions.reduce((max, entry) => Math.max(max, numberOfName(entry.name) + 1), 1),
    questions.length + 1,
  )
  return { format: QUESTIONS_FORMAT, next, questions }
}

/**
 * Replace one chapter's questions atomically.
 * @param {string} libraryDir - library root.
 * @param {string} book - book id.
 * @param {string} code - chapter code.
 * @param {unknown} body - `{ questions, next }` from the browser.
 * @returns {Promise<{ format: number, next: number, questions: object[] }>} what was stored.
 */
export async function writeQuestions(libraryDir, book, code, body) {
  if (!isSegment(book) || !CODE.test(code)) throw new Error('书或章不合法')
  const record = body !== null && typeof body === 'object' ? body : {}
  const raw = Array.isArray(record.questions) ? record.questions : []
  const questions = []
  const seen = new Set()
  for (const value of raw) {
    const entry = sanitizeQuestion(value, questions.length)
    if (entry === null || seen.has(entry.id)) continue
    seen.add(entry.id)
    questions.push(entry)
    if (questions.length >= MAX_QUESTIONS) break
  }
  const wantedNext = Number(record.next)
  const next = Math.max(
    Number.isFinite(wantedNext) && wantedNext > 0 ? Math.round(wantedNext) : 1,
    questions.reduce((max, entry) => Math.max(max, numberOfName(entry.name) + 1), 1),
    questions.length + 1,
  )
  const target = questionsFile(libraryDir, book, code)
  await mkdir(dirname(target), { recursive: true })
  const temporary = `${target}.${process.pid}.tmp`
  await writeFile(temporary, `${JSON.stringify({ format: QUESTIONS_FORMAT, book, code, next, questions }, null, 2)}\n`, 'utf8')
  await rename(temporary, target)
  return { format: QUESTIONS_FORMAT, next, questions }
}
